// Builds /assets/worldmap.js: a compact equirectangular world map keyed by
// ISO 3166-1 alpha-2, plus a tiny renderer that fills each species' countries
// on the range map (`.rangemap[data-cc][data-vg]` divs on species pages).
//
// Source: Natural Earth 110m admin-0 countries (public domain), cached next to
// this script as ne_110m_admin_0_countries.geojson. Re-run only when the map
// itself needs rebuilding: node build/species/build-worldmap.js
const fs = require('fs');
const path = require('path');

const SRC = path.join(__dirname, 'ne_110m_admin_0_countries.geojson');
const OUT = path.join(__dirname, '..', '..', 'assets', 'worldmap.js');

const gj = JSON.parse(fs.readFileSync(SRC, 'utf8'));
const W = 1000;
const TOP = 84;      // clip the empty high Arctic
const BOT = -58;     // Antarctica is skipped entirely
const S = W / 360;
const H = Math.round((TOP - BOT) * S);

const px = (lon) => +((lon + 180) * S).toFixed(1);
const py = (lat) => +((TOP - Math.max(BOT, Math.min(TOP, lat))) * S).toFixed(1);

const paths = {};
let skipped = [];
for (const f of gj.features) {
  const p = f.properties;
  let cc = p.ISO_A2 && p.ISO_A2 !== '-99' ? p.ISO_A2 : p.ISO_A2_EH;
  if (!cc || cc === '-99') { skipped.push(p.NAME); continue; }
  if (cc === 'AQ') continue;
  const geom = f.geometry;
  const polys = geom.type === 'Polygon' ? [geom.coordinates] : geom.coordinates;
  let d = '';
  for (const poly of polys) {
    for (const ring of poly) {
      let last = null;
      const pts = [];
      for (const [lon, lat] of ring) {
        const x = px(lon); const y = py(lat);
        if (last && Math.abs(x - last[0]) < 1 && Math.abs(y - last[1]) < 1) continue;
        pts.push([x, y]); last = [x, y];
      }
      if (pts.length < 3) continue;
      d += 'M' + pts.map((q) => q[0] + ' ' + q[1]).join('L') + 'Z';
    }
  }
  if (d) paths[cc] = (paths[cc] || '') + d;
}

const js = `// Generated by build/species/build-worldmap.js. Map data: Natural Earth 110m
// admin-0 countries (public domain). Fills .rangemap[data-cc] divs.
(function(){
var VB='0 0 ${W} ${H}';
var LAND=${JSON.stringify(paths)};
function split(v){v=(v||'').toUpperCase();return v?v.split(/\\s+/):[]}
function render(el){
  var i,have={},vg={};
  var cc=split(el.getAttribute('data-cc'));for(i=0;i<cc.length;i++)have[cc[i]]=1;
  var vv=split(el.getAttribute('data-vg'));for(i=0;i<vv.length;i++)vg[vv[i]]=1;
  var s='<svg viewBox="'+VB+'" role="img">';
  for(var k in LAND){
    var cls=have[k]?'mp in':(vg[k]?'mp vg':'mp');
    s+='<path class="'+cls+'" d="'+LAND[k]+'"/>';
  }
  el.innerHTML=s+'</svg>';
}
var els=document.querySelectorAll('.rangemap');
for(var i=0;i<els.length;i++)render(els[i]);
// Exposed for pages that draw their own overlays (the cams map).
window.BBMap={viewBox:VB,land:LAND};
})();
`;
fs.writeFileSync(OUT, js);
console.log(`countries: ${Object.keys(paths).length} | skipped (no ISO code): ${skipped.join(', ') || 'none'}`);
console.log(`wrote ${OUT} (${(js.length / 1024).toFixed(0)} KB)`);
